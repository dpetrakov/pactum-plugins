import test from "node:test";
import assert from "node:assert/strict";
import http from "node:http";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "../plugins/document-review/node_modules/playwright/index.mjs";
const site = fileURLToPath(new URL("../site", import.meta.url));
const types = { ".html": "text/html", ".css": "text/css", ".js": "text/javascript", ".mjs": "text/javascript", ".svg": "image/svg+xml" };
test("interactive product examples preserve personal state and support keyboard/touch", { timeout: 60000 }, async () => {
  const server = http.createServer(async (req, res) => {
    try {
      const relative = decodeURIComponent(new URL(req.url, "http://localhost").pathname);
      const file = path.resolve(site, `.${relative === "/" ? "/index.html" : relative}`);
      if (!file.startsWith(`${site}${path.sep}`)) throw new Error("outside site");
      const bytes = await fs.readFile(file); res.setHeader("content-type", types[path.extname(file)] || "application/octet-stream"); res.end(bytes);
    } catch { res.statusCode = 404; res.end("Not found"); }
  });
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const browser = await chromium.launch({ headless: true });
  const errors = [];
  try {
    const base = `http://127.0.0.1:${server.address().port}`;
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(base);
    assert.equal(await page.locator("#review-progress").textContent(), "2 unread changes");
    await page.locator("#read-all").click();
    assert.equal(await page.locator("#review-progress").textContent(), "All changes read by Alex");
    await page.locator("#undo-read").click();
    assert.equal(await page.locator("#review-progress").textContent(), "2 unread changes");
    await page.locator("#open-comment").click();
    await page.keyboard.press("Escape"); assert.equal(await page.locator("#open-comment").evaluate(e => e === document.activeElement), true);
    await page.locator("#open-comment").click();
    await page.locator("#comment-text").fill("Add a human review before release.");
    await page.locator("#save-comment").click();
    assert.equal(await page.locator("#send-count").textContent(), "1");
    await page.locator("#send-agent").click();
    await page.waitForFunction(() => document.querySelector("#agent-state").textContent === "Ready for your review");
    assert.equal(await page.locator("#review-document").getByText("a human review", { exact: false }).count() > 0, true);
    await page.getByRole("button", { name: "Accept response", exact: true }).click();
    assert.equal(await page.locator("#agent-state").textContent(), "Response accepted by Alex");
    assert.equal(await page.locator("#review-progress").textContent(), "2 unread changes", "acceptance must not read on a person's behalf");
    await page.locator("#reader-sam").click();
    await page.getByRole("button", { name: "Mark architecture/decisions.md read as Sam Chen", exact: true }).click();
    assert.equal(await page.locator("#sam-count").textContent(), "0 unread");
    assert.equal(await page.locator("#alex-count").textContent(), "3 unread");
    await page.locator("#team-note-text").fill("<img src=x onerror=alert(1)>");
    await page.getByRole("button", { name: "Save shared note", exact: true }).click();
    await page.locator("#reader-alex").click();
    assert.match(await page.locator("#team-notes").textContent(), /<img src=x/); assert.equal(await page.locator("#team-notes img").count(), 0);
    await page.locator('[data-root="generated"]').click();
    assert.match(await page.locator("#team-file-list").textContent(), /generated\/api-reference/);
    await page.locator('[data-root="generated"]').click();
    assert.doesNotMatch(await page.locator("#team-file-list").textContent(), /generated\/api-reference/);
    const divider = page.locator('[data-column="0"]'); await divider.focus(); await page.keyboard.press("ArrowRight");
    assert.equal(await divider.getAttribute("aria-valuenow"), "228");
    const box = await divider.boundingBox(); await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 60, box.y + box.height / 2); await page.mouse.up();
    assert.equal(await divider.getAttribute("aria-valuenow"), "288");
    await page.locator("#reset-columns").click(); assert.equal(await divider.getAttribute("aria-valuenow"), "220");
    await page.locator("#diagrams").scrollIntoViewIfNeeded(); await page.waitForSelector("#diagram-canvas svg");
    const node = page.getByRole("button", { name: /^Node Human review:/ });
    await node.focus(); await page.keyboard.press("Enter"); await page.keyboard.press("ArrowRight"); await page.keyboard.press("Enter");
    await page.waitForFunction(() => document.querySelector("#diagram-feedback").textContent.includes("Personal layout updated"));
    await page.keyboard.press("c"); await page.locator("#diagram-comment-text").fill("Name the reviewer.");
    await page.locator("#diagram-comment-form").getByRole("button", { name: "Save note", exact: true }).click();
    assert.match(await page.locator("#diagram-feedback").textContent(), /Human review: Name the reviewer/);
    await page.locator("#diagram-source").click(); assert.equal(await page.locator("#diagram-code").isVisible(), true);
    await page.locator("#diagram-source").click(); await page.locator("#diagram-changes").click(); assert.equal(await page.locator("#diagram-change-list").isVisible(), false);
    await page.locator("#theme-toggle").click(); assert.equal(await page.locator("html").getAttribute("class"), "dark");
    assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), "auto");
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, reducedMotion: "reduce" });
    mobile.on("pageerror", error => errors.push(error.message));
    await mobile.goto(base); await mobile.locator("#read-all").tap();
    assert.match(await mobile.locator("#review-progress").textContent(), /All changes read/);
    await mobile.locator("#diagrams").scrollIntoViewIfNeeded(); await mobile.waitForSelector("#diagram-canvas svg");
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const rect = await mobile.locator("#read-all").boundingBox(); assert.ok(rect.width >= 40 && rect.height >= 40);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
});
